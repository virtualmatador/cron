#include <iostream>
#include <sstream>

#include "cron.hpp"

void check_next(std::string_view cron_expression, std::string_view in,
                std::string_view out) {
  cronio::cron<true> cron{cron_expression};
  std::tm tm_in = {};
  std::ispanstream{in} >> std::get_time(&tm_in, "%Y-%m-%d %H:%M:%S");
  auto tm_out = cron.next(tm_in);
  auto str_out =
      (std::stringstream{} << std::put_time(&tm_out, "%Y-%m-%d %H:%M:%S"))
          .str();
  if (str_out != out) {
    throw std::runtime_error(std::string{cron_expression});
  }
}

